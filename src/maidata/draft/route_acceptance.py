def validate_route_loss(mode, vocabulary):
    if mode not in ('ce', 'acceptance37'):
        raise ValueError('reconstruction_route_loss must be ce or acceptance37')
    if mode == 'acceptance37' and vocabulary != AXIS15_37:
        raise ValueError('acceptance37 requires reconstruction_route_vocabulary=axis15-37')


def route_loss_recipe(config):
    """Bind the actual fixed objective; old recipes without this knob mean CE."""
    mode = config.get('reconstruction_route_loss', 'ce')
    validate_route_loss(mode, config.get('reconstruction_route_vocabulary', 'route71'))
    result = {'reconstruction_route_loss': mode}
    if mode == 'acceptance37':
        result['reconstruction_route_acceptance'] = [list(row) for row in ACCEPTANCE37]
    return result


@lru_cache(maxsize=None)
def _log_acceptance(device):
    import torch
    return torch.tensor(ACCEPTANCE37, dtype=torch.float32, device=device).log()


def acceptance_nll(logits, labels, *, matrix=None):
    """Per-row -log(sum A[y,j]*p[j]), computed in FP32 log space.

    The optional matrix supports independent numerical checks; training always
    uses the fixed source table, reused per device and never registered in R.
    """
    import torch
    from torch.nn import functional as F
    log_weights = (_log_acceptance(logits.device) if matrix is None else
                   torch.as_tensor(matrix, dtype=torch.float32, device=logits.device).log())
    return -torch.logsumexp(F.log_softmax(logits.float(), dim=-1)
                           + log_weights.index_select(0, labels), dim=-1)
